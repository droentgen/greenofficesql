/** Turn a prepared statement into plain SQL text for seed.sql (values are quoted safely). */
function inline_sql(string $sql, array $params): string
{
    $i = 0;
    return preg_replace_callback('/\?/', function () use (&$i, $params) {
        $v = $params[$i++];
        if ($v === null) {
            return 'NULL';
        }
        if (is_int($v) || is_float($v)) {
            return (string)$v;
        }
        return "'" . str_replace("'", "''", (string)$v) . "'";
    }, $sql);
}
